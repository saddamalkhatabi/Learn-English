import { chromium } from "playwright";
import assert from "node:assert/strict";
const root=process.env.G9_SMOKE_URL || "http://127.0.0.1:3178/";
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
const errors=[],bad=[];
page.on("pageerror",e=>errors.push(e.message));
page.on("response",r=>{if(r.status()>=400&&/\.(js|json|mp3)/.test(r.url()))bad.push(r.status()+" "+r.url())});
try{
 await page.goto(root,{waitUntil:"networkidle",timeout:30000});
 const scriptResponse=await page.request.get(new URL("group-nine.js",root).toString());
 assert.equal(scriptResponse.status(),200,"Group Nine JavaScript must be served by the local server");
 await page.locator('[data-view="group-nine"]').click();
 await page.locator("#g9PatternList .g9PatternChip").first().waitFor({timeout:15000});
 assert.equal(await page.locator("#g9PatternList .g9PatternChip").count(),18);
 const source=await page.evaluate(async()=>await (await fetch("data/group-nine.json")).json());
 assert.equal(source.items.length,18);
 assert.equal(source.chapters.length,3);

assert.equal((await page.locator("#g9Title").innerText()).trim(),"because");
 assert.equal(await page.locator("#g9SceneSteps button").count(),4);
 assert.equal((await page.locator("#g9MainEnglish").innerText()).trim(),"I stayed inside because it was raining.");
 assert.equal(await page.locator("#g9ChapterTabs button").count(),3);
 assert.equal(await page.locator("#g9ChapterLines button").count(),6);
 assert.match(await page.locator("#g9Visual").innerText(),/مشهد توضيحي مؤقت/);
 assert.equal(await page.locator("#g9Visual img").count(),0);
 const sentence="I stayed inside because it was raining.";
 await page.locator("#g9QuizOptions button").filter({hasText:sentence}).click();
 assert.match(await page.locator("#g9QuizFeedback").innerText(),/أحسنت/);
 const words=sentence.split(/\s+/);
 for(let i=0;i<words.length;i++) await page.locator('[data-g9-token="'+i+'"]').click();
 assert.match(await page.locator("#g9Progress").innerText(),/1 \/ 72/);
 await page.locator("#g9ChapterTabs [data-g9-chapter='1']").click();
 assert.match(await page.locator("#g9ChapterLines").innerText(),/Huda prefers reading, while Omar enjoys listening./);
 await page.locator("#g9StoryToggle").click();
 assert.equal(await page.locator("#g9StoryList .g9StoryRow").count(),2);
 await page.locator('[data-g9-pattern="17"]').first().click();
 assert.equal((await page.locator("#g9Title").innerText()).trim(),"even if");
 assert.equal(await page.locator("#g9SceneSteps button").count(),4);
 assert.equal(await page.locator("#g9ChapterTabs button").count(),3);
 assert.equal(await page.locator("#g9Visual img").count(),0);
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2);
 assert.equal(overflow,false,"Mobile horizontal overflow");
 await page.reload({waitUntil:"networkidle"});
 await page.locator('[data-view="group-nine"]').click();
 await page.locator("#g9PatternList .g9PatternChip").first().waitFor();
 assert.match(await page.locator("#g9Progress").innerText(),/1 \/ 72/);
 await page.locator('[data-view="group-three"]').click();
 await page.locator("#g3PatternList .g3PatternChip").first().waitFor();
 assert.equal(await page.locator("#g3PatternList .g3PatternChip").count(),18);
 await page.locator('[data-view="group-two"]').click();
 await page.locator("#g2PatternList .g2PatternChip").first().waitFor();
 assert.equal(await page.locator("#g2PatternList .g2PatternChip").count(),18);
 await page.locator('[data-view="group-one"]').click();
 await page.locator("#g1PatternList .g1PatternChip").first().waitFor();
 assert.equal(await page.locator("#g1PatternList .g1PatternChip").count(),18);
 assert.deepEqual(errors,[]);
 assert.deepEqual(bad,[]);
 console.log("OK mobile smoke: 18 group-nine patterns, quiz, word builder, 3 chapter stories, progress, zero broken assets; groups one through eight intact");
}finally{await browser.close()}
