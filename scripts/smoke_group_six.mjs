import { chromium } from "playwright";
import assert from "node:assert/strict";
const root=process.env.G6_SMOKE_URL || "http://127.0.0.1:3178/";
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
const errors=[],bad=[];
page.on("pageerror",e=>errors.push(e.message));
page.on("response",r=>{if(r.status()>=400&&/\.(js|json|mp3)/.test(r.url()))bad.push(r.status()+" "+r.url())});
try{
 await page.goto(root,{waitUntil:"networkidle",timeout:30000});
 const scriptResponse=await page.request.get(new URL("group-six.js",root).toString());
 assert.equal(scriptResponse.status(),200,"Group Six JavaScript must be served by the local server");
 await page.locator('[data-view="group-six"]').click();
 await page.locator("#g6PatternList .g6PatternChip").first().waitFor({timeout:15000});
 assert.equal(await page.locator("#g6PatternList .g6PatternChip").count(),18);
 const source=await page.evaluate(async()=>await (await fetch("data/group-six.json")).json());
 assert.equal(source.items.length,18);
 assert.equal(source.chapters.length,3);

assert.equal((await page.locator("#g6Title").innerText()).trim(),"I\u0027ll");
 assert.equal(await page.locator("#g6SceneSteps button").count(),4);
 assert.equal((await page.locator("#g6MainEnglish").innerText()).trim(),"I'll call you after class.");
 assert.equal(await page.locator("#g6ChapterTabs button").count(),3);
 assert.equal(await page.locator("#g6ChapterLines button").count(),6);
 assert.match(await page.locator("#g6Visual").innerText(),/مشهد توضيحي مؤقت/);
 assert.equal(await page.locator("#g6Visual img").count(),0);
 const sentence="I'll call you after class.";
 await page.locator("#g6QuizOptions button").filter({hasText:sentence}).click();
 assert.match(await page.locator("#g6QuizFeedback").innerText(),/أحسنت/);
 const words=sentence.split(/\s+/);
 for(let i=0;i<words.length;i++) await page.locator('[data-g6-token="'+i+'"]').click();
 assert.match(await page.locator("#g6Progress").innerText(),/1 \/ 72/);
 await page.locator("#g6ChapterTabs [data-g6-chapter='1']").click();
 assert.match(await page.locator("#g6ChapterLines").innerText(),/The presentation starts at nine on Monday./);
 await page.locator("#g6StoryToggle").click();
 assert.equal(await page.locator("#g6StoryList .g6StoryRow").count(),2);
 await page.locator('[data-g6-pattern="17"]').first().click();
 assert.equal((await page.locator("#g6Title").innerText()).trim(),"As soon as ..., I\u0027ll");
 assert.equal(await page.locator("#g6SceneSteps button").count(),4);
 assert.equal(await page.locator("#g6ChapterTabs button").count(),3);
 assert.equal(await page.locator("#g6Visual img").count(),0);
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2);
 assert.equal(overflow,false,"Mobile horizontal overflow");
 await page.reload({waitUntil:"networkidle"});
 await page.locator('[data-view="group-six"]').click();
 await page.locator("#g6PatternList .g6PatternChip").first().waitFor();
 assert.match(await page.locator("#g6Progress").innerText(),/1 \/ 72/);
 await page.locator('[data-view="group-three"]').click();
 await page.locator("#g3PatternList .g3PatternChip").first().waitFor();
 assert.equal(await page.locator("#g3PatternList .g3PatternChip").count(),18);
 await page.locator('[data-view="group-two"]').click();
 await page.locator("#g2PatternList .g2PatternChip").first().waitFor();
 assert.equal(await page.locator("#g2PatternList .g2PatternChip").count(),18);
 await page.locator('[data-view="group-one"]').click();
 await page.locator("#g1PatternList .g1PatternChip").first().waitFor();
 assert.equal(await page.locator("#g1PatternList .g1PatternChip").count(),18);
 assert.deepEqual(errors,[]);
 assert.deepEqual(bad,[]);
 console.log("OK mobile smoke: 18 group-six patterns, quiz, word builder, 3 chapter stories, progress, zero broken assets; groups one through five intact");
}finally{await browser.close()}
