import { chromium } from "playwright";
import assert from "node:assert/strict";
const root=process.env.G8_SMOKE_URL || "http://127.0.0.1:3178/";
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
const errors=[],bad=[];
page.on("pageerror",e=>errors.push(e.message));
page.on("response",r=>{if(r.status()>=400&&/\.(js|json|mp3)/.test(r.url()))bad.push(r.status()+" "+r.url())});
try{
 await page.goto(root,{waitUntil:"networkidle",timeout:30000});
 const scriptResponse=await page.request.get(new URL("group-eight.js",root).toString());
 assert.equal(scriptResponse.status(),200,"Group Eight JavaScript must be served by the local server");
 await page.locator('[data-view="group-eight"]').click();
 await page.locator("#g8PatternList .g8PatternChip").first().waitFor({timeout:15000});
 assert.equal(await page.locator("#g8PatternList .g8PatternChip").count(),18);
 const source=await page.evaluate(async()=>await (await fetch("data/group-eight.json")).json());
 assert.equal(source.items.length,18);
 assert.equal(source.chapters.length,3);

assert.equal((await page.locator("#g8Title").innerText()).trim(),"Excuse me");
 assert.equal(await page.locator("#g8SceneSteps button").count(),4);
 assert.equal((await page.locator("#g8MainEnglish").innerText()).trim(),"Excuse me, is this seat free?");
 assert.equal(await page.locator("#g8ChapterTabs button").count(),3);
 assert.equal(await page.locator("#g8ChapterLines button").count(),6);
 assert.match(await page.locator("#g8Visual").innerText(),/مشهد توضيحي مؤقت/);
 assert.equal(await page.locator("#g8Visual img").count(),0);
 const sentence="Excuse me, is this seat free?";
 await page.locator("#g8QuizOptions button").filter({hasText:sentence}).click();
 assert.match(await page.locator("#g8QuizFeedback").innerText(),/أحسنت/);
 const words=sentence.split(/\s+/);
 for(let i=0;i<words.length;i++) await page.locator('[data-g8-token="'+i+'"]').click();
 assert.match(await page.locator("#g8Progress").innerText(),/1 \/ 72/);
 await page.locator("#g8ChapterTabs [data-g8-chapter='1']").click();
 assert.match(await page.locator("#g8ChapterLines").innerText(),/Lina said, 'Let's start near the park.'/);
 await page.locator("#g8StoryToggle").click();
 assert.equal(await page.locator("#g8StoryList .g8StoryRow").count(),2);
 await page.locator('[data-g8-pattern="17"]').first().click();
 assert.equal((await page.locator("#g8Title").innerText()).trim(),"Let me know if");
 assert.equal(await page.locator("#g8SceneSteps button").count(),4);
 assert.equal(await page.locator("#g8ChapterTabs button").count(),3);
 assert.equal(await page.locator("#g8Visual img").count(),0);
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2);
 assert.equal(overflow,false,"Mobile horizontal overflow");
 await page.reload({waitUntil:"networkidle"});
 await page.locator('[data-view="group-eight"]').click();
 await page.locator("#g8PatternList .g8PatternChip").first().waitFor();
 assert.match(await page.locator("#g8Progress").innerText(),/1 \/ 72/);
 await page.locator('[data-view="group-three"]').click();
 await page.locator("#g3PatternList .g3PatternChip").first().waitFor();
 assert.equal(await page.locator("#g3PatternList .g3PatternChip").count(),18);
 await page.locator('[data-view="group-two"]').click();
 await page.locator("#g2PatternList .g2PatternChip").first().waitFor();
 assert.equal(await page.locator("#g2PatternList .g2PatternChip").count(),18);
 await page.locator('[data-view="group-one"]').click();
 await page.locator("#g1PatternList .g1PatternChip").first().waitFor();
 assert.equal(await page.locator("#g1PatternList .g1PatternChip").count(),18);
 assert.deepEqual(errors,[]);
 assert.deepEqual(bad,[]);
 console.log("OK mobile smoke: 18 group-eight patterns, quiz, word builder, 3 chapter stories, progress, zero broken assets; groups one through seven intact");
}finally{await browser.close()}
